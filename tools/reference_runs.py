#!/usr/bin/env python3
"""Resultados de referencia LOCALES para la pagina del proyecto (issue #9).

Corre greedy, exacto y QAOA sobre los tres casos empaquetados usando el mismo
bridge que la app de Qollab, pero con el BasicSimulator local de Qiskit. No
envia jobs remotos. Escribe en docs/results/:

  reference.json        resultados completos por caso y presupuesto
  REFERENCE.md          tabla resumen
  coverage.png          cobertura real por metodo y caso
  qaoa_<caso>.png       distribucion de mediciones QAOA (top selecciones)
  map_caba-comuna4.png  mapa de zonas, sitios y selecciones greedy/exacta

Uso (matplotlib solo se usa aca, no en Qollab):
  uv run --no-project --with-requirements requirements.txt --with matplotlib \
      python tools/reference_runs.py [--plots-only]
"""

import copy
import json
import platform
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import qiskit  # noqa: E402
from qiskit.providers.basic_provider import BasicSimulator  # noqa: E402

from ambulance import bridge  # noqa: E402

OUT = ROOT / "docs" / "results"
CASES = ("synthetic", "caba-comuna4", "caba")
SHOTS = 1024
SIM_SEED = 11
BUDGETS = {
    # Lo que usa la app en Qollab (defaults de bridge.run_quantum).
    "app": {"layers": 3, "restarts": 2, "maxiter": 150},
    # Presupuesto de optimizar() en baseline.py.
    "baseline": {"layers": 3, "restarts": 4, "maxiter": 500},
}

SURFACE, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
COLORS = {"greedy": "#2a78d6", "exact": "#eb6834", "qaoa": "#1baf7a"}
LABELS = {"greedy": "Greedy", "exact": "Exact", "qaoa": "QAOA (best valid shot)"}
CASE_LABELS = {
    "synthetic": "Synthetic (pitch example)",
    "caba-comuna4": "CABA Comuna 4",
    "caba": "CABA full city",
}


def style(ax):
    ax.set_facecolor(SURFACE)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=INK2)


def run_all():
    results = {}
    for case_id in CASES:
        case_json = bridge.case_data(case_id)
        results[case_id] = {}
        for name, budget in BUDGETS.items():
            out = json.loads(bridge.run_quantum(
                case_json, BasicSimulator(seed_simulator=SIM_SEED), shots=SHOTS,
                seed=1, **budget))
            results[case_id][name] = out
            q = out["qaoa"]
            print(f"{case_id:13s} {name:8s} status={q['status']} "
                  f"greedy={out['greedy']['coverage_pct']:.1f}% "
                  f"exact={out['exact']['coverage_pct']:.1f}% "
                  f"qaoa={q['coverage_pct']:.1f}% "
                  f"P(opt)={q['optimal_probability']:.3f} "
                  f"uniform={q['uniform_optimal_probability']:.3f}")
    return results


def fmt_weight(v, units):
    return f"{v:,.0f} {'thousand' if 'thousand' in units else 'people'}"


def write_table(results):
    lines = [
        "# Reference results (local simulator)",
        "",
        "Generated by `tools/reference_runs.py` with Qiskit's local "
        f"`BasicSimulator(seed_simulator={SIM_SEED})`, {SHOTS} shots, through the "
        "same `ambulance.bridge.run_quantum` the Qollab app calls. These are "
        "**not** Qollab, IonQ or hardware results; they are the baseline to compare "
        "real Qollab runs against. Sampling and optimizer outcomes vary across "
        "Qiskit/NumPy/SciPy versions.",
        "",
        f"Environment: Python {platform.python_version()}, Qiskit {qiskit.__version__}.",
        "",
        "| Case | Optimizer budget | Greedy | Exact | QAOA best valid shot | Valid shots | P(optimum) QAOA | P(optimum) random | Amplification |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for case_id, by_budget in results.items():
        for name, out in by_budget.items():
            g, e, q = out["greedy"], out["exact"], out["qaoa"]
            b = BUDGETS[name]
            lines.append(
                f"| {CASE_LABELS[case_id]} | {name}: {b['restarts']}×{b['maxiter']} it, "
                f"p={b['layers']} | {g['coverage_pct']:.1f}% | {e['coverage_pct']:.1f}% | "
                f"{q['coverage_pct']:.1f}% | {100 * q['valid_shot_rate']:.0f}% | "
                f"{100 * q['optimal_probability']:.1f}% | "
                f"{100 * q['uniform_optimal_probability']:.1f}% | "
                f"{q['optimal_probability_amplification']:.2f}× |")
    lines += [
        "",
        "Coverage = population inside the radius of at least one selected site "
        "(straight-line distance, not road travel time). \"Amplification\" = "
        "P(optimum) under QAOA / P(optimum) choosing K sites uniformly at random.",
        "",
        "Inputs per case:",
        "",
    ]
    for case_id, by_budget in results.items():
        out = by_budget["app"]
        g, e = out["greedy"], out["exact"]
        lines.append(
            f"- **{CASE_LABELS[case_id]}** (`{case_id}` rev {out['case_revision']}, "
            f"fingerprint `{out['input_fingerprint'][:12]}`): K={e['k']}, "
            f"{e['n_sites']} sites, radius {e['radius_km']} km, total "
            f"{fmt_weight(e['total_weight'], e['weight_units'])}. Greedy sites "
            f"{g['selected_site_indices']}, exact {e['selected_site_indices']} "
            f"({e['n_optimal_solutions']} optimal selection(s)).")
    (OUT / "REFERENCE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def plot_coverage(results):
    fig, ax = plt.subplots(figsize=(8, 4.2), dpi=150, facecolor=SURFACE)
    style(ax)
    methods = ("greedy", "exact", "qaoa")
    h = 0.24
    for ci, case_id in enumerate(CASES):
        out = results[case_id]["app"]
        for mi, m in enumerate(methods):
            v = out[m]["coverage_pct"]
            y = ci + (mi - 1) * (h + 0.03)
            ax.barh(y, v, height=h, color=COLORS[m],
                    label=LABELS[m] if ci == 0 else None)
            ax.text(v + 0.8, y, f"{v:.1f}%", va="center", fontsize=8, color=INK)
    ax.set_yticks(range(len(CASES)), [CASE_LABELS[c] for c in CASES], color=INK)
    ax.invert_yaxis()
    ax.set_xlim(0, 100)
    ax.set_xlabel("Population covered (%)", color=INK2)
    ax.xaxis.grid(True, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    ax.set_title("Actual coverage by method (K=3, local simulator)",
                 loc="left", color=INK, fontsize=11)
    ax.legend(frameon=False, loc="lower right", fontsize=8, labelcolor=INK)
    fig.tight_layout()
    fig.savefig(OUT / "coverage.png", facecolor=SURFACE)
    plt.close(fig)


def plot_distribution(case_id, out, top=10):
    q, e = out["qaoa"], out["exact"]
    n = e["n_sites"]
    optimal = {tuple(sorted(s)) for s in e["optimal_selections"]}
    freq = Counter()
    for bits, c in q["counts"].items():
        sites = tuple(i for i in range(n) if bits[n - 1 - i] == "1")
        if len(sites) == e["k"]:
            freq[sites] += c
    items = freq.most_common(top)
    shots = q["shots"]
    fig, ax = plt.subplots(figsize=(8, 4), dpi=150, facecolor=SURFACE)
    style(ax)
    for i, (sites, c) in enumerate(items):
        is_opt = sites in optimal
        ax.bar(i, 100 * c / shots, width=0.7,
               color=COLORS["qaoa"] if is_opt else "#b9b8b2")
        ax.text(i, 100 * c / shots + 0.3, f"{100 * c / shots:.1f}%",
                ha="center", fontsize=7, color=INK)
    ax.axhline(100 / len(list(_combos(n, e["k"]))), color=INK2, linestyle="--",
               linewidth=1)
    ax.text(len(items) - 0.6, ax.get_ylim()[1] * 0.92,
            "dashed line: uniform random, per selection", ha="right",
            fontsize=7, color=INK2)
    ax.set_xticks(range(len(items)), [str(list(s)) for s, _ in items],
                  rotation=40, ha="right", fontsize=7, color=INK)
    ax.set_ylabel("Share of shots (%)", color=INK2)
    ax.yaxis.grid(True, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    ax.set_title(f"{CASE_LABELS[case_id]}: most measured site selections "
                 f"({shots} shots; green = optimal)", loc="left", color=INK,
                 fontsize=10)
    fig.tight_layout()
    fig.savefig(OUT / f"qaoa_{case_id}.png", facecolor=SURFACE)
    plt.close(fig)


def _combos(n, k):
    from itertools import combinations
    return combinations(range(n), k)


def plot_map(case_id, out):
    case = json.loads(bridge.case_data(case_id))
    zones, sites, r = case["zones"], case["sites"], case["radius_km"]
    g = set(out["greedy"]["selected_site_indices"])
    e = set(out["exact"]["selected_site_indices"])
    wmax = max(z["weight"] for z in zones)
    fig, axes = plt.subplots(1, 2, figsize=(10, 5), dpi=150, facecolor=SURFACE,
                             sharex=True, sharey=True)
    for ax, (m, sel) in zip(axes, (("greedy", g), ("exact", e))):
        style(ax)
        covered = set(out[m]["covered_zone_ids"])
        ax.scatter([z["x_km"] for z in zones], [z["y_km"] for z in zones],
                   s=[2 + 30 * z["weight"] / wmax for z in zones],
                   c=[COLORS[m] if z["id"] in covered else "#c9c8c2" for z in zones],
                   linewidths=0, alpha=0.8)
        for i, s in enumerate(sites):
            chosen = i in sel
            if chosen:
                ax.add_patch(plt.Circle((s["x_km"], s["y_km"]), r, fill=False,
                                        color=COLORS[m], linewidth=1.5))
            ax.plot(s["x_km"], s["y_km"], marker="^" if chosen else "o",
                    markersize=9 if chosen else 6,
                    color=INK if chosen else "#8a8984",
                    markeredgecolor=SURFACE, markeredgewidth=1.5)
            ax.annotate(str(i), (s["x_km"], s["y_km"]), xytext=(5, 4),
                        textcoords="offset points", fontsize=7, color=INK)
        ax.set_aspect("equal")
        ax.set_title(f"{LABELS[m].split(' (')[0]}: sites {sorted(sel)} → "
                     f"{out[m]['coverage_pct']:.1f}% covered", loc="left",
                     color=INK, fontsize=10)
        ax.set_xlabel("km (EPSG:9498 easting)", color=INK2, fontsize=8)
    axes[0].set_ylabel("km (northing)", color=INK2, fontsize=8)
    fig.suptitle(f"{CASE_LABELS[case_id]}: K={len(e)}, radius {r} km "
                 "(colored = covered census tracts, triangles = chosen bases)",
                 x=0.01, ha="left", color=INK, fontsize=10)
    fig.tight_layout()
    fig.savefig(OUT / f"map_{case_id}.png", facecolor=SURFACE)
    plt.close(fig)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    if "--plots-only" in sys.argv:  # regrafica desde reference.json, sin correr
        results = json.loads((OUT / "reference.json").read_text())["results"]
        plot_coverage(results)
        for case_id in CASES:
            plot_distribution(case_id, results[case_id]["app"])
        return
    results = run_all()
    slim = copy.deepcopy(results)
    for by in slim.values():  # covered_zone_ids es grande y reconstruible
        for o in by.values():
            for m in ("greedy", "exact", "qaoa"):
                o[m].pop("covered_zone_ids", None)
    meta = {"shots": SHOTS, "seed_simulator": SIM_SEED, "budgets": BUDGETS,
            "backend": "qiskit BasicSimulator (local)",
            "python": platform.python_version(), "qiskit": qiskit.__version__}
    (OUT / "reference.json").write_text(
        json.dumps({"meta": meta, "results": slim}, indent=1), encoding="utf-8")
    write_table(results)
    plot_coverage(results)
    for case_id in CASES:
        plot_distribution(case_id, results[case_id]["app"])
    plot_map("caba-comuna4", results["caba-comuna4"]["app"])
    print(f"wrote {OUT.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
